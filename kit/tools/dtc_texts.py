"""Fault texts for the Fault Scanner (the head unit has no fault text database).

    dtc_texts.py <DTC export .txt> [out.js]      texts for the faults in a coding tool's export
    dtc_texts.py --db <zip | .tgz | folder> [out_dir]   a fault text database for every control unit
    dtc_texts.py --codes <.csv> [out_dir]        an OBD fault code list (code,description) - engine
                                                 and transmission only, run after --db

Export: coding tools (e.g. a BimmerCode / E-Sys style backup) write the car's fault memory with texts:

    /// ATM2 [61] - Telematic Communication Box ///
    026104 -> TCB: Internal SWT check failed

This turns such an export into apps/dtc_scanner/dtc_texts.js ("61:026104" -> text), which the
Fault Scanner shows next to each fault it reads. Fault codes are per control unit, so the key is
address + code. Only faults in the export get a text: export again after new faults and rebuild.

Database (--db): an oap-dtcscan package (the zip, its .tgz or an unpacked folder) holds the fault
texts of every control unit type: sgbd_index.json ("<address> <SGBD index>" -> SGBD),
texts/<SGBD>.json (code -> text), unit_names.json (SGBD -> name) and dtc_texts.json
("<address>:<code>" -> text). Only those data files are copied, to apps/dtc_scanner/dtc_db/; the
scanner asks each unit with faults for its SGBD index (UDS 22 F1 50) and looks its texts up there.

OBD code list (--codes): a CSV of code + description (BMW_Fault_Codes.csv) holds the OBD (SAE)
description of each code, with no control unit. Its codes mean other things in other units, so the
scanner uses it only for the engine and transmission units (DME/DDE, EGS) and only where the
database has no English text; it shows them as "OBD: ...". Codes with more than one description in
the list, and placeholders (DUMMY_SAE), are left out. Written to <out_dir>/obd_texts.json.

Only English texts are imported: one with German in it (german_words.txt) is left out, and the
scanner shows no text for that fault. The texts are BMW's: they stay out of git (.gitignore).
"""
import json, os, re, shutil, sys, tarfile, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, '..', '..', 'apps', 'dtc_scanner')


def from_export(src, out):
    texts, addr = {}, None
    for line in open(src, encoding='utf-8', errors='replace'):
        m = re.match(r'\s*///\s*\S+\s*\[([0-9A-Fa-f]{1,2})\]', line)
        if m:
            addr = m.group(1).upper().zfill(2)
            continue
        m = re.match(r'\s*([0-9A-Fa-f]{6})\s*->\s*(.+?)\s*$', line)
        if m and addr and not re.match(r'(?i)no description', m.group(2)) and is_english(m.group(2)):
            # plain ASCII: drawn with the app's baked fonts
            texts[addr + ':' + m.group(1).upper()] = re.sub(r'[^\x20-\x7e]', '', m.group(2))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write("'use strict';\n// generated by kit/tools/dtc_texts.py from %s - fault texts for one car, not in git\n" % os.path.basename(src))
        f.write('module.exports = ' + json.dumps(texts, indent=1, sort_keys=True) + ';\n')
    print('%d fault texts -> %s' % (len(texts), os.path.normpath(out)))


def _members(src):
    """{path inside: bytes reader} of a zip, tar(.gz) or folder."""
    if os.path.isdir(src):
        out = {}
        for d, _, names in os.walk(src):
            for n in names:
                p = os.path.join(d, n)
                out[os.path.relpath(p, src).replace(os.sep, '/')] = (lambda p=p: open(p, 'rb').read())
        return out
    if zipfile.is_zipfile(src):
        z = zipfile.ZipFile(src)
        return {n: (lambda n=n: z.read(n)) for n in z.namelist() if not n.endswith('/')}
    if tarfile.is_tarfile(src):
        t = tarfile.open(src)
        return {m.name: (lambda m=m: t.extractfile(m).read()) for m in t.getmembers() if m.isfile()}
    sys.exit('%s: not a folder, zip or tar(.gz)' % src)


def _strings(data, what):
    d = json.loads(data.decode('utf-8'))
    if not isinstance(d, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in d.items()):
        sys.exit('%s: not a JSON object of texts' % what)
    return d


# English only: a text with a German word in it (german_words.txt, or an umlaut / sharp s) is left
# out, and the Fault Scanner shows no text for that fault. Signal identifiers (Fehler_Status_LIN),
# short words and abbreviations (ABS, DASS) are not looked at; whole words in capitals are
# (KILOMETERSTAND).
GERMAN = {w.strip() for w in open(os.path.join(HERE, 'german_words.txt'), encoding='utf-8')
          if w.strip() and not w.startswith('#')}
_WORD = re.compile(r"[A-Za-zÄÖÜäöüß][A-Za-zÄÖÜäöüß0-9_\-]*")


def is_english(t):
    for w in _WORD.findall(t):
        if '_' in w or any(c.isdigit() for c in w):
            continue
        for p in w.split('-'):
            if re.search('[äöüßÄÖÜ]', p) or (len(p) >= (5 if p.isupper() else 3) and p.lower() in GERMAN):
                return False
    return True


def english(d, n):
    """The English texts of d; n counts [kept, left out]."""
    out = {k: v for k, v in d.items() if is_english(v)}
    n[0] += len(out)
    n[1] += len(d) - len(out)
    return out


def from_db(src, out):
    files = _members(src)
    idx = sorted((p for p in files if p == 'sgbd_index.json' or p.endswith('/sgbd_index.json')), key=len)
    if not idx:
        # a zip that only carries the package as a .tgz
        tgz = [p for p in files if p.endswith('.tgz')]
        if tgz:
            tmp = os.path.join(os.path.dirname(os.path.abspath(out)), '.dtc_db_package.tgz')
            with open(tmp, 'wb') as f:
                f.write(files[tgz[0]]())
            try:
                return from_db(tmp, out)
            finally:
                os.remove(tmp)
        sys.exit('%s: no sgbd_index.json - not an oap-dtcscan package?' % src)
    base = idx[0][:-len('sgbd_index.json')]
    sgbd = _strings(files[idx[0]](), 'sgbd_index.json')
    texts, n = {}, [0, 0]
    for p in files:
        m = re.match(re.escape(base) + r'texts/([A-Za-z0-9_]+)\.json$', p)
        if m:
            texts[m.group(1)] = english(_strings(files[p](), p), n)
    tmp = out.rstrip('/\\') + '.new'
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(os.path.join(tmp, 'texts'))
    with open(os.path.join(tmp, 'sgbd_index.json'), 'w', encoding='utf-8') as f:
        json.dump(sgbd, f, ensure_ascii=False)
    for name in ('unit_names.json', 'dtc_texts.json'):
        if base + name in files:
            with open(os.path.join(tmp, name), 'w', encoding='utf-8') as f:
                json.dump(english(_strings(files[base + name](), name), n if name == 'dtc_texts.json' else [0, 0]), f,
                          ensure_ascii=False)
    for name, d in texts.items():
        with open(os.path.join(tmp, 'texts', name + '.json'), 'w', encoding='utf-8') as f:
            json.dump(d, f, ensure_ascii=False, separators=(',', ':'))
    shutil.rmtree(out, ignore_errors=True)
    os.replace(tmp, out)
    print('%d control unit types, %d fault texts -> %s' % (len(texts), sum(len(d) for d in texts.values()), os.path.normpath(out)))
    print('%d English texts imported, %d German ones left out (no text shown for those)' % tuple(n))


def from_codes(src, out):
    import csv
    seen = {}
    with open(src, encoding='utf-8-sig', errors='replace', newline='') as f:
        for row in csv.reader(f):
            if len(row) < 2 or not re.fullmatch(r'[0-9A-Fa-f]{6}', row[0].strip()):
                continue                                    # header, blank lines
            t = re.sub(r'\s+', ' ', row[1].split('\n')[0].replace('"', "'")).strip()
            if t and 'DUMMY' not in t:
                seen.setdefault(row[0].strip().upper(), {}).setdefault(t.lower(), t)
    texts, n = {}, [0, 0]
    for code, ts in seen.items():
        if len(ts) == 1:                                    # one meaning only
            t = re.sub(r'[^\x20-\x7e]', '', next(iter(ts.values())))
            if is_english(t):
                texts[code] = t
                n[0] += 1
            else:
                n[1] += 1
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'obd_texts.json'), 'w', encoding='utf-8') as f:
        json.dump(texts, f, ensure_ascii=False, separators=(',', ':'))
    print('%d OBD codes -> %s (%d with more than one description and %d German ones left out)'
          % (len(texts), os.path.join(os.path.normpath(out), 'obd_texts.json'), len(seen) - len(texts) - n[1], n[1]))


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    if sys.argv[1] == '--db':
        if len(sys.argv) < 3:
            sys.exit(__doc__)
        from_db(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else os.path.join(APP, 'dtc_db'))
    elif sys.argv[1] == '--codes':
        if len(sys.argv) < 3:
            sys.exit(__doc__)
        from_codes(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else os.path.join(APP, 'dtc_db'))
    else:
        from_export(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.join(APP, 'dtc_texts.js'))
